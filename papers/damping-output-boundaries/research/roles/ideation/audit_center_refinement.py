"""Independent exact audit of the center Taylor estimate from own frozen witness."""
from datetime import datetime, timezone, timedelta
from fractions import Fraction as F
from pathlib import Path
import hashlib
import json
import math
import platform

HERE = Path(__file__).resolve().parent
SOURCE = HERE / "double-zero-result.json"


def main():
    raw_bytes = SOURCE.read_bytes()
    source = json.loads(raw_bytes.decode("utf-8"))
    rs = list(map(F, source["max_abs_normalized_residues"]))
    ws = list(map(F, source["parameters"]["omega"]))
    zetas = list(map(F, [source["parameters"]["zeta0"], source["parameters"]["zeta1"]]))
    sqrt_lower = [F(499,500), F(249,250)]
    for z, q in zip(zetas, sqrt_lower):
        assert q > 0 and q*q < 1-z*z
    m_bounds = [sum(2*abs(r)/(q*z**3*w**4) for r,w in zip(rs,ws))
                for z,q in zip(zetas,sqrt_lower)]
    h_imag = F(source["H1"]["imag_exact"])
    # With u=sin^2(pi*x/2), a''/pi^2=3u-4u^2. Critical u=3/8
    # gives 9/16, endpoints give 0,-1; hence absolute supremum is 1.
    curvature_values = [F(0), F(9,16), F(-1)]
    assert max(map(abs,curvature_values)) == 1
    assert m_bounds[0] < 162 and m_bounds[1] < 40
    assert h_imag > F(113,1000000)
    # pi < 22/7, (22/7)^2 < 10. The classical pi bound itself is not
    # generated by this code; the second inequality is checked exactly.
    assert F(22,7)**2 < 10
    rows = []
    for t in [1920,2990,3000,4800,10000]:
        p0 = F(810,t*t)
        p1 = F(113,1000000)-F(200,t*t)
        rows.append({"T_s":t,"input_duration_s":2*t,
                     "P0_strict_upper":str(p0),"P1_strict_lower":str(p1),
                     "ratio_strict_lower":str(p1/p0),"ratio_approx":float(p1/p0)})
    assert F(rows[2]["ratio_strict_lower"]) == F(817,810)
    # Exact margin giving ratio>1: 113*T^2 > 1,010,000,000.
    first_integer_t = math.isqrt(1010000000//113)+1
    assert first_integer_t == 2990
    assert 113*first_integer_t**2 > 1010000000
    assert 113*(first_integer_t-1)**2 <= 1010000000
    out = {"time_Asia_Shanghai":datetime.now(timezone(timedelta(hours=8))).isoformat(),
           "python_version":platform.python_version(),
           "source":SOURCE.name,"source_sha256":hashlib.sha256(raw_bytes).hexdigest(),
           "script_sha256":hashlib.sha256(Path(__file__).read_bytes()).hexdigest(),
           "m02_rational_upper":str(m_bounds[0]),"m12_rational_upper":str(m_bounds[1]),
           "m02_upper_approx":float(m_bounds[0]),"m12_upper_approx":float(m_bounds[1]),
           "H1_imag_exact":str(h_imag),"curvature_factor_values":list(map(str,curvature_values)),
           "first_integer_T_guaranteeing_ratio_above_one_under_outer_bounds":first_integer_t,
           "rows":rows,
           "scope":"Exact arithmetic audit of an analytic varying-input-family bound; no time integration or engineering prediction."}
    (HERE/"center-refinement-audit.json").write_text(json.dumps(out,ensure_ascii=False,indent=2)+"\n",encoding="utf-8")
    print(json.dumps(out,ensure_ascii=False,indent=2))


if __name__ == "__main__":
    main()
